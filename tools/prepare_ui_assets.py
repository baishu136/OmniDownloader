class PDFPen(BasePen):
    def __init__(self): super().__init__(None); self.commands=[]
    def _moveTo(self,p): self.commands.append('%g %g m' % p)
    def _lineTo(self,p): self.commands.append('%g %g l' % p)
    def _curveToOne(self,a,b,c): self.commands.append('%g %g %g %g %g %g c' % (*a,*b,*c))
    def _closePath(self): self.commands.append('h')
    def _endPath(self): pass

def pdf(svg):
    tree=ET.fromstring(svg);commands=['q','1 0 0 -1 0 24 cm','0 g']
    for node in tree.iter():
        if node.tag.endswith('path') and node.get('fill')!='none' and node.get('d'):
            pen=PDFPen();parse_path(node.get('d'),pen);commands += pen.commands+['f']
    commands.append('Q');stream=('\n'.join(commands)+'\n').encode()
    objects=[b'<< /Type /Catalog /Pages 2 0 R >>',b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
             b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 24 24] /Resources << >> /Contents 4 0 R >>',
             b'<< /Length '+str(len(stream)).encode()+b' >>\nstream\n'+stream+b'endstream']
    result=b'%PDF-1.4\n';offsets=[0]
    for i,obj in enumerate(objects,1): offsets.append(len(result));result+=f'{i} 0 obj\n'.encode()+obj+b'\nendobj\n'
    xref=len(result);result+=b'xref\n0 5\n0000000000 65535 f \n'
    result+=b''.join(f'{n:010d} 00000 n \n'.encode() for n in offsets[1:])
    return result+f'trailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n'.encode()

def main():
    SOURCE.mkdir(parents=True,exist_ok=True)
    def download(item):
        category,name=item;path=SOURCE/(name+'.svg')
        if not path.exists():
            url=f'https://raw.githubusercontent.com/google/material-design-icons/master/src/{category}/{name}/materialiconsoutlined/24px.svg'
            r=requests.get(url,timeout=30);r.raise_for_status();path.write_bytes(r.content)
        return name,path.read_bytes()
    artwork=dict(ThreadPoolExecutor(6).map(download,sorted(set(ICONS.values()))))
    provenance={'repository':'https://github.com/google/material-design-icons','style':'Material Icons Outlined 24px','sha256':{name:hashlib.sha256(data).hexdigest() for name,data in artwork.items()}}
    (SOURCE/'sources.json').write_text(json.dumps(provenance,indent=2)+'\n',encoding='utf-8')
    license=SOURCE/'LICENSE.txt'
    if not license.exists():
        r=requests.get('https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE',timeout=30);r.raise_for_status();license.write_bytes(r.content)
    for name,data in artwork.items():
        dest=ASSETS/f'material_{name}.imageset';dest.mkdir(parents=True,exist_ok=True)
        (dest/'icon.pdf').write_bytes(pdf(data))
        (dest/'Contents.json').write_text(json.dumps({'images':[{'filename':'icon.pdf','idiom':'universal'}],'info':{'author':'xcode','version':1},'properties':{'preserves-vector-representation':True,'template-rendering-intent':'template'}},indent=2)+'\n')
    aliases={key:'material_'+value[1] for key,value in ICONS.items()}
    swift='import SwiftUI\n\n/// Vector artwork shared with Android Material Outlined. Generated by tools/prepare_ui_assets.py.\nstruct OmniIcon: View {\n    let name: String\n    var size: CGFloat = 24\n    private static let assets: [String:String] = [\n'
    swift+=''.join(f'        "{key}": "{value}",\n' for key,value in sorted(aliases.items()))
    swift+='    ]\n    var body: some View {\n        Group {\n            if let asset = Self.assets[name] { Image(asset).renderingMode(.template).resizable().scaledToFit() }\n            else { Image(systemName: name).resizable().scaledToFit() }\n        }.frame(width: size, height: size).accessibilityHidden(true)\n    }\n}\n'
    (ROOT/'OmniDownloader-iOS/OmniDownloader/Views/OmniIcon.swift').write_text(swift,encoding='utf-8')
    # One rounded vector defines the edge. No pre-rounded bitmap, white matte or outer CSS border.
    cloud=ET.fromstring(artwork['cloud_download']);paths=''.join(ET.tostring(n,encoding='unicode') for n in cloud if n.tag.endswith('path') and n.get('fill')!='none')
    defs='<defs><linearGradient id="brand" x2="1" y2="1"><stop stop-color="#3B5BDB"/><stop offset="1" stop-color="#725572"/></linearGradient><clipPath id="edge"><rect width="96" height="96" rx="30"/></clipPath></defs>'
    logo=f'<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">{defs}<g clip-path="url(#edge)"><rect width="96" height="96" fill="url(#brand)"/><g transform="translate(23 23) scale(2.083333)" fill="white">{paths}</g></g></svg>'
    brand=ROOT/'shared/icons/brand.svg';brand.write_text(logo,encoding='utf-8')
    web=ROOT/'windows/web';(web/'static/logo.svg').write_text(logo,encoding='utf-8')
    png=resvg_py.svg_to_bytes(svg_string=logo,width=1024,height=1024)
    image=Image.open(io.BytesIO(png))
    image.save(web/'static/logo.png');image.resize((128,128),Image.Resampling.LANCZOS).save(web/'static/logo_128.png')
    image.save(web/'logo.png')
    # Render every ICO frame directly from vectors. Downsampling 1024px with Lanczos
    # can introduce nonzero alpha at the 16px corners, outside the intended curve.
    sizes=[16,24,32,48,64,128,256]
    frames=[resvg_py.svg_to_bytes(svg_string=logo,width=n,height=n) for n in sizes]
    directory=bytearray(struct.pack('<HHH',0,1,len(sizes)));offset=6+16*len(sizes)
    for n,data in zip(sizes,frames):
        directory.extend(struct.pack('<BBBBHHII',n%256,n%256,0,0,1,32,len(data),offset));offset+=len(data)
    ico=bytes(directory)+b''.join(frames)
    for dest in [ROOT/'windows/app.ico',web/'static/favicon.ico',web/'favicon.ico']: dest.write_bytes(ico)
    # iOS applies its own app-icon mask: fill the full square, with no baked corner or shadow.
    app_logo=logo.replace('<g clip-path="url(#edge)">','<g>')
    icon=Image.open(io.BytesIO(resvg_py.svg_to_bytes(svg_string=app_logo,width=1024,height=1024))).convert('RGB')
    icon.save(ASSETS/'AppIcon.appiconset/icon.png')
    print('Prepared',len(artwork),'vector icons and shared, single-edge brand artwork')

if __name__=='__main__': main()
