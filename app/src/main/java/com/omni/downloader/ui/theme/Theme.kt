/**
 * 应用内的语义状态色。
 * 通过 CompositionLocal 注入，深色模式下自动切换为高对比变体，
 * 避免在卡片内部硬编码亮色常量导致暗色可读性下降。
 */
@Immutable
data class OmniStatusColors(
    val success: Color,
    val warning: Color,
    val error: Color,
    val info: Color
)

val LocalStatusColors = staticCompositionLocalOf {
    OmniStatusColors(
        success = SuccessGreen,
        warning = WarningOrange,
        error = ErrorRed,
        info = LightPrimary
    )
}

